// Generates the supported commands data from the code: the site's
// commands page lists every command, the core README a summary per category.
// Usage: node scripts/commands.mjs [--check]  (after pnpm build)
//
// With --check, it exits with an error instead of writing when a file is
// out of date, for CI.
import { readFileSync, writeFileSync } from "node:fs";
import commands from "../packages/zpl/build/commands.js";
import { parsedCommands } from "../packages/zpl/build/parse.js";
import { renderedCommands } from "../packages/render/build/support.js";

const root = new URL("../", import.meta.url);
const docsData = new URL("apps/site/content/commands.json", root);
const readme = new URL("packages/zpl/README.md", root);
const docsUrl = "https://zplkit.fingal.dev/docs/commands";

const groups = {
  "Labels and formats": ["^XA", "^XZ", "^LH", "^LL", "^LR", "^LS", "^LT", "^PW", "^PO", "^PM", "^DF", "^XF", "^MU", "^CC", "~CC", "^CD", "~CD", "^CT", "~CT"],
  "Text and fonts": ["^A", "^A@", "^CF", "^CI", "^CW", "^FB", "^FH", "^SE", "~DB", "~DE", "~DS", "~DT", "~DU"],
  "Graphics and images": ["~DG", "~DY", "~EG", "~DN", "^XG", "^IL", "^IM", "^IS", "^ID", "^HG", "^HY"],
};

/** Barcodes, fields and graphics go by prefix; everything else is printer setup */
const categoryOf = (code) => {
  for (const [name, codes] of Object.entries(groups)) {
    if (codes.includes(code)) return name;
  }
  if (code.startsWith("^B")) return "Barcodes";
  if (code.startsWith("^G")) return "Graphics and images";
  if (code.startsWith("^F") || code === "^SF" || code === "^SN") return "Fields";
  return "Printer and media";
};

const categories = [
  "Labels and formats",
  "Fields",
  "Text and fonts",
  "Graphics and images",
  "Barcodes",
  "Printer and media",
];

/** Limits worth knowing about, shown next to the command */
const notes = {
  "^A@": "Needs the font file, downloaded in the label or passed to the renderer",
  "^B7": "Same size as a printer's symbol; error correction codewords can differ",
  "^BD": "Modes 2 to 6",
  "^BX": "Same size as a printer's symbol; data can be encoded differently",
  "^BF": "Same size as a printer's symbol; data can be encoded differently",
  "^BR": "Types 1 to 6; composite symbols show a placeholder",
  "^CI": "UTF-8 (28 to 30) and Latin-1",
  "^GS": "The UL and CSA marks are drawn as stand-ins",
  "~DT": "Bounded fonts use Zebra's own format, which isn't drawn",
  "~DY": "TrueType fonts and graphics",
};

/** Supported, with differences the notes explain */
const partial = new Set(["^CI", "^GS", "^BR"]);

/** Commands with nothing to draw, besides printer setup */
const nothingToDraw = new Set(["^FX", "^ID", "~DN", "~EG", "^HG", "^HY"]);

const parsed = new Set(parsedCommands);
const rendered = new Set(renderedCommands);
const all = Object.entries(commands).map(([code, name]) => {
  const category = categoryOf(code);
  const drawn = rendered.has(code)
    ? partial.has(code)
      ? "partial"
      : "yes"
    : category === "Printer and media" || nothingToDraw.has(code)
    ? "n/a"
    : "no";
  // Supported means it's read, written and, if it draws anything, drawn
  const support = !parsed.has(code)
    ? "no"
    : drawn === "partial" || drawn === "no"
    ? "partial"
    : "yes";
  return {
    code,
    name,
    category,
    support,
    // Whether the renderer draws it, so the reference can show an example
    drawn: rendered.has(code),
    note: notes[code] ?? "",
  };
});
const supported = all.filter((command) => command.support !== "no");

const data = JSON.stringify({ categories, commands: all }, null, 2) + "\n";

const summary = [
  "<!-- commands:start (generated by scripts/commands.mjs) -->",
  "",
  `zplkit currently supports ${supported.length} of the ${all.length} commands in Zebra's ZPL II Programming Guide. Other commands are kept as they are by \`parse()\` and can be added with \`raw()\`. The [full reference](${docsUrl}) has notes on each command.`,
  "",
  "| Category | Supported |",
  "| --- | --- |",
  ...categories.map((category) => {
    const rows = all.filter((command) => command.category === category);
    const codes = rows.filter((command) => command.support !== "no").map(({ code }) => `\`${code}\``);
    return `| ${category} (${codes.length} of ${rows.length}) | ${codes.join(" ") || "None yet"} |`;
  }),
  "",
  "<!-- commands:end -->",
].join("\n");

const current = readFileSync(readme, "utf8");
const start = current.indexOf("<!-- commands:start");
const end = current.indexOf("<!-- commands:end -->");
if (start < 0 || end < 0) throw new Error("README.md has no commands markers");
const newReadme =
  current.slice(0, start) + summary + current.slice(end + "<!-- commands:end -->".length);

const outdated = [];
for (const [file, content] of [
  [docsData, data],
  [readme, newReadme],
]) {
  let existing = "";
  try {
    existing = readFileSync(file, "utf8");
  } catch {
    // Not generated yet
  }
  if (existing === content) continue;
  if (process.argv.includes("--check")) outdated.push(file.pathname);
  else writeFileSync(file, content);
}

if (outdated.length) {
  console.error(
    `Out of date, run node scripts/commands.mjs:\n${outdated.join("\n")}`
  );
  process.exit(1);
}

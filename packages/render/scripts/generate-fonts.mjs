// Embed the fonts in src/fonts: font 0's stand-in with its measured advances
// and ink, and DejaVu Sans Mono for the bitmap fonts A to H
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const font = readFileSync(new URL("fonts/font0.ttf", root)).toString("base64");
const advances = JSON.parse(
  readFileSync(new URL("fonts/font0-advances.json", root), "utf8")
);
const ink = JSON.parse(
  readFileSync(new URL("fonts/font0-ink.json", root), "utf8")
);

// Advances as "codePoint:width" pairs; characters without a glyph are left out
const table = Object.entries(advances)
  .filter(([, width]) => width !== null)
  .map(([code, width]) => `${Number(code).toString(36)}:${width}`)
  .join(",");

// Ink extents as "codePoint:left:right" triples; characters drawn stretched
// to their advance are left out
const inkTable = Object.entries(ink)
  .filter(([, extent]) => extent !== null)
  .map(([code, [left, right]]) => `${Number(code).toString(36)}:${left}:${right}`)
  .join(",");

writeFileSync(
  new URL("src/fonts/font0.ts", root),
  `// Generated by scripts/generate-fonts.mjs from fonts/font0.ttf (Archivo, SIL Open
// Font License 1.1, see fonts/OFL.txt), fonts/font0-advances.json and
// fonts/font0-ink.json. Don't edit.

/** The font file, base64-encoded */
export const font0Data =
  "${font}";

/** Advance widths at ^A0N,100,100 by code point, as base-36 code:width pairs */
export const font0Advances = "${table}";

/**
 * Where each character's ink starts and ends after the pen at ^A0N,100,100,
 * as base-36 code:left:right triples
 */
export const font0Ink = "${inkTable}";
`
);
console.log(
  `font0.ts: ${font.length} base64 characters, ${
    table.split(",").length
  } advances`
);

const dejavu = (file) =>
  readFileSync(new URL(`fonts/${file}`, root)).toString("base64");
writeFileSync(
  new URL("src/fonts/dejavu.ts", root),
  `// Generated by scripts/generate-fonts.mjs from fonts/DejaVuSansMono*.ttf
// (DejaVu fonts, see fonts/LICENSE-DejaVu.txt). Don't edit.

/** DejaVu Sans Mono, base64-encoded */
export const dejavuMonoData =
  "${dejavu("DejaVuSansMono.ttf")}";

/** DejaVu Sans Mono Bold, base64-encoded */
export const dejavuMonoBoldData =
  "${dejavu("DejaVuSansMono-Bold.ttf")}";
`
);
console.log("dejavu.ts written");
